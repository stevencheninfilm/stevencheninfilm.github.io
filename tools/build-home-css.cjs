#!/usr/bin/env node
'use strict';

// Keep this order aligned with the homepage's original stylesheet cascade.
// Other pages continue to load the individual source stylesheets.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = 'assets/home-critical.bundle.css';
const SOURCES = Object.freeze([
  'assets/site.css',
  'assets/home-v2.css',
  'assets/home-opening.css',
  'assets/banner-v3.css',
  'assets/portfolio.css',
  'assets/cinema-workflows.css',
  'assets/dlss-detail.css',
  'assets/cat-nest-home.css',
  'assets/tvc-transition.css',
  'assets/xuantian-brand.css',
  'assets/icp-footer.css',
  'assets/media-access.css',
  'assets/progressive-video-status.css',
  'assets/home-locales.css',
  'assets/site-language.css',
  'assets/home-refinements.css',
]);

function renderBundle(root = ROOT) {
  const sections = SOURCES.map((source) => {
    // Keeping the output beside every source preserves CSS url(...) resolution.
    if (path.dirname(source) !== path.dirname(OUTPUT)) {
      throw new Error(`CSS URL rebasing is required before bundling ${source}`);
    }
    const css = fs.readFileSync(path.join(root, source), 'utf8');
    // These rules cannot simply be moved into the middle of a concatenated file.
    const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
    if (/^\s*@(charset|import)\b/im.test(withoutComments)) {
      throw new Error(`Resolve @charset/@import before bundling ${source}`);
    }
    return `/* Source: ${source} */\n${css.trimEnd()}\n`;
  });
  return '/* Generated by node tools/build-home-css.cjs. Do not edit this file.\n' +
    ' * Edit the source stylesheets, rebuild, and bump the homepage bundle URL.\n' +
    ' * Verify freshness with: node tools/build-home-css.cjs --check\n */\n\n' +
    sections.join('\n');
}

function isCurrent(root = ROOT) {
  const output = path.join(root, OUTPUT);
  return fs.existsSync(output) && fs.readFileSync(output, 'utf8') === renderBundle(root);
}

function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length && args[0] !== '--check')) {
    throw new Error('Usage: node tools/build-home-css.cjs [--check]');
  }
  if (args[0] === '--check') {
    if (!isCurrent()) throw new Error(`${OUTPUT} is stale. Run node tools/build-home-css.cjs`);
    console.log(`${OUTPUT} is current (${SOURCES.length} source stylesheets).`);
    return;
  }
  const bundle = renderBundle();
  fs.writeFileSync(path.join(ROOT, OUTPUT), bundle);
  console.log(`Built ${OUTPUT}: ${SOURCES.length} stylesheets, ${Buffer.byteLength(bundle)} bytes.`);
}

if (require.main === module) {
  try { main(); } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = { OUTPUT, SOURCES, renderBundle, isCurrent };
