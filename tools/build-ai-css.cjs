#!/usr/bin/env node
'use strict';

// Keep the established AI page cascade; the bundle stays beside its sources so
// relative font/image URLs resolve identically.
const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
const OUTPUT = 'assets/ai-critical.bundle.css';
const SOURCES = Object.freeze([
  'site.css', 'portfolio.css', 'industry-partnerships.css',
  'cinema-workflows.css', 'ai-news.css', 'xuantian-brand.css',
  'icp-footer.css', 'media-access.css', 'site-language.css',
  'ai-locales.css', 'progressive-video-status.css', 'ai-polish.css',
].map(name => `assets/${name}`));

function renderBundle(root = ROOT) {
  return '/* Generated by node tools/build-ai-css.cjs. Edit source stylesheets and rebuild. */\n\n' +
    SOURCES.map(source => {
      const css = fs.readFileSync(path.join(root, source), 'utf8').trimEnd();
      if (/^\s*@(charset|import)\b/im.test(css.replace(/\/\*[\s\S]*?\*\//g, ''))) {
        throw new Error(`Resolve @charset/@import before bundling ${source}`);
      }
      return `/* Source: ${source} */\n${css}\n`;
    }).join('\n');
}

function main() {
  const bundle = renderBundle();
  const output = path.join(ROOT, OUTPUT);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== bundle) {
      throw new Error(`${OUTPUT} is stale. Run node tools/build-ai-css.cjs`);
    }
    console.log(`${OUTPUT} is current.`);
  } else {
    fs.writeFileSync(output, bundle);
    console.log(`Built ${OUTPUT}: ${SOURCES.length} sources, ${Buffer.byteLength(bundle)} bytes.`);
  }
}
if (require.main === module) main();
module.exports = { OUTPUT, SOURCES, renderBundle };
